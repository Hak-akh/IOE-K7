// 2. Update all bo00.json ... bo14.json and public/bo00.json ... public/bo14.json
let totalQuestionsWithTrans = 0;
let totalQuestions = 0;

for (let i = 0; i <= 14; i++) {
  const fName = `bo${String(i).padStart(2, '0')}.json`;
  if (fs.existsSync(fName)) {
    const data = JSON.parse(fs.readFileSync(fName, 'utf8'));
    data.questions.forEach(q => {
      totalQuestions++;
      const full = reconstructSentence(q.question, q.answer, q.type, q.options);
      const trans = translations[full] 
                 || translations[full.replace(/([a-z])([A-Z])/g, '$1 $2')] 
                 || translations[q.answer] 
                 || translations[q.question];

      if (trans) {
        q.vietnameseTranslation = trans;
        if (!q.learning) q.learning = {};
        q.learning.vietnameseTranslation = trans;
        q.learning.translation = trans;
        totalQuestionsWithTrans++;
      } else if (q.vietnameseTranslation && !q.vietnameseTranslation.includes('Bản dịch hỗ trợ')) {
        totalQuestionsWithTrans++;
      }
    });

    fs.writeFileSync(fName, JSON.stringify(data, null, 2), 'utf8');

    // Also update in public/
    const pubPath = path.join('public', fName);
    if (fs.existsSync(pubPath)) {
      fs.writeFileSync(pubPath, JSON.stringify(data, null, 2), 'utf8');
    }
  }
}

console.log(`Summary: ${totalQuestionsWithTrans} / ${totalQuestions} questions across all 15 sets have Vietnamese translations!`);
