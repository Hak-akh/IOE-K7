function reconstructSentence(q, a, type, options) {
  if (!q) return a || '';
  if (type === 'word-order' || type === 'word_order') return a || '';
  const isPromptOnly = /^(listen and|listen to|choose the|odd one out|find the|which word)/i.test(q.trim());
  if (isPromptOnly && a && a.length > 2 && !/^[A-D]$/i.test(a.trim())) return a.trim();
  let cleanQ = q.replace(/\s+[A-D]\.\s+.*?\b[B-D]\.\s+.*$/i, '').trim();
  if (cleanQ.includes('_')) return cleanQ.replace(/(_\s*)+/g, a || '');
  if (cleanQ.includes('…') || cleanQ.includes('...')) return cleanQ.replace(/(\.{3,}|…)/g, a || '');
  if (isPromptOnly && a) return a;
  return cleanQ;
}

